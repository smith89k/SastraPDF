// Copies the PDF libraries from node_modules into app/vendor so the app runs fully offline.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'app', 'vendor');
fs.rmSync(out, { recursive: true, force: true });   // generated folder: start clean so old files don't ship
fs.mkdirSync(out, { recursive: true });

const files = [
  'pdfjs-dist/build/pdf.min.mjs',
  'pdfjs-dist/build/pdf.worker.min.mjs',
  'pdf-lib/dist/pdf-lib.min.js',
  'jszip/dist/jszip.min.js'
];
// pdf.js support files: image decoders for scanned pages (JBIG2, JPEG 2000) and colour profiles,
// the 14 standard PDF fonts, and character maps for Chinese/Japanese/Korean text.
// quickjs-eval.* runs scripts inside PDF forms, which the app never does, so it stays out.
const dirs = ['wasm', 'standard_fonts', 'cmaps'];
const skip = f => /^quickjs-eval\./.test(f);

const need = src => { if (!fs.existsSync(src)) { console.error('Missing ' + src + ' — run "npm install" again.'); process.exit(1); } };
for (const f of files) {
  const src = path.join(root, 'node_modules', f); need(src);
  fs.copyFileSync(src, path.join(out, path.basename(f)));
  console.log('vendor: ' + path.basename(f));
}
for (const d of dirs) {
  const src = path.join(root, 'node_modules', 'pdfjs-dist', d); need(src);
  const dst = path.join(out, 'pdfjs', d); fs.mkdirSync(dst, { recursive: true });
  const list = fs.readdirSync(src).filter(f => !skip(f));
  for (const f of list) fs.copyFileSync(path.join(src, f), path.join(dst, f));
  console.log('vendor: pdfjs/' + d + '/ (' + list.length + ' files)');
}

// UI fonts ship inside the app (the app makes no network requests on its own): Fontsource's
// @font-face rules for the weights the UI uses, Latin and Khmer subsets only, woff2 only,
// merged into vendor/fonts/fonts.css. Other scripts fall back to Segoe UI.
const fonts = { 'ibm-plex-sans': [400, 500, 600], 'ibm-plex-mono': [400, 500], 'noto-sans-khmer': [400, 500, 600] };
const subsets = /-(latin|latin-ext|khmer)-\d+-normal \*\//;
const fdir = path.join(out, 'fonts'); fs.mkdirSync(fdir, { recursive: true });
let css = '/* generated by scripts/copy-vendor.js from @fontsource packages (SIL OFL 1.1) */\n';
for (const [fam, weights] of Object.entries(fonts)) {
  const pkg = path.join(root, 'node_modules', '@fontsource', fam); need(pkg);
  fs.mkdirSync(path.join(fdir, fam), { recursive: true });
  fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(fdir, fam, 'LICENSE'));
  for (const w of weights) {
    for (const rule of fs.readFileSync(path.join(pkg, w + '.css'), 'utf8').split(/(?=\/\* )/)) {
      if (!subsets.test(rule)) continue;
      const file = rule.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      fs.copyFileSync(path.join(pkg, 'files', file), path.join(fdir, fam, file));
      css += rule.replace(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\), url\([^)]+\.woff\) format\('woff'\)/, `url(./${fam}/$1) format('woff2')`);
    }
  }
}
fs.writeFileSync(path.join(fdir, 'fonts.css'), css);
console.log('vendor: fonts/ (' + Object.keys(fonts).join(', ') + ')');
